// Packs the files in public/ into src/static-files.js so the Worker can serve them itself.
// Runs automatically before `wrangler dev` and `wrangler deploy` (see "build" in wrangler.jsonc).
import {readdirSync, readFileSync, writeFileSync, statSync} from 'node:fs';
import {join, relative, extname} from 'node:path';
import {createHash} from 'node:crypto';

const ROOT = new URL('../public/', import.meta.url).pathname;
const TYPES = {'.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
  '.webmanifest': 'application/manifest+json', '.png': 'image/png', '.svg': 'image/svg+xml', '.ico': 'image/x-icon'};
const walk = d => readdirSync(d).flatMap(f => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const out = {};
for (const file of walk(ROOT)){
  const type = TYPES[extname(file)];
  if (!type) continue;
  const buf = readFileSync(file);
  out['/' + relative(ROOT, file).split('\\').join('/')] = {type, b64: buf.toString('base64'), etag: '"' + createHash('sha1').update(buf).digest('hex').slice(0, 16) + '"'};
}
writeFileSync(new URL('../src/static-files.js', import.meta.url), '// Generated by scripts/bundle-static.mjs. Do not edit.\nexport default ' + JSON.stringify(out) + ';\n');
console.log('bundled', Object.keys(out).length, 'static files');
